#!/usr/bin/env node
/**
 * Bundle Cursor SDK runtime into src-tauri/resources/cursor-runtime/
 * so packaged .app/.dmg builds can run AI review without the CI checkout path.
 *
 * Usage:
 *   node scripts/prepare-cursor-runtime.mjs [--skip-install]
 */
import { execFileSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

export const RUNTIME_DIR_NAME = "cursor-runtime";
export const RUNTIME_SCRIPT_NAME = "cursor-local-prompt.mjs";

export function repoRoot(fromDir = __dirname) {
  return path.resolve(fromDir, "..");
}

export function runtimeOutDir(root = repoRoot()) {
  return path.join(root, "src-tauri", "resources", RUNTIME_DIR_NAME);
}

export function sourceScriptPath(root = repoRoot()) {
  return path.join(root, "scripts", RUNTIME_SCRIPT_NAME);
}

export function readSdkVersion(root = repoRoot()) {
  const pkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
  const raw = pkg.dependencies?.["@cursor/sdk"];
  if (!raw || typeof raw !== "string") {
    throw new Error("package.json is missing dependencies.@cursor/sdk");
  }
  return raw.replace(/^[\^~>=<\s]+/, "");
}

export function buildRuntimePackageJson(sdkVersion) {
  return {
    name: "im-review-cursor-runtime",
    private: true,
    type: "module",
    engines: { node: ">=22.13" },
    dependencies: {
      "@cursor/sdk": sdkVersion,
    },
  };
}

/** Candidate script locations for packaged + dev layouts (mirrors Rust resolver). */
export function candidateRuntimeScriptPaths(resourceDir, projectRoot) {
  const out = [];
  if (resourceDir) {
    out.push(path.join(resourceDir, RUNTIME_DIR_NAME, RUNTIME_SCRIPT_NAME));
    out.push(
      path.join(
        resourceDir,
        "resources",
        RUNTIME_DIR_NAME,
        RUNTIME_SCRIPT_NAME,
      ),
    );
  }
  if (projectRoot) {
    out.push(path.join(projectRoot, "scripts", RUNTIME_SCRIPT_NAME));
  }
  return out;
}

export function writeRuntimeScaffold({
  outDir,
  sdkVersion,
  scriptSrc,
  skipInstall = false,
}) {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });

  if (!existsSync(scriptSrc)) {
    throw new Error(`missing Cursor script source at ${scriptSrc}`);
  }
  cpSync(scriptSrc, path.join(outDir, RUNTIME_SCRIPT_NAME));

  const pkg = buildRuntimePackageJson(sdkVersion);
  writeFileSync(
    path.join(outDir, "package.json"),
    `${JSON.stringify(pkg, null, 2)}\n`,
  );

  writeFileSync(
    path.join(outDir, "README.md"),
    [
      "# cursor-runtime",
      "",
      "Generated by `scripts/prepare-cursor-runtime.mjs` during `tauri build`.",
      "Do not edit by hand. Contents are gitignored except `.gitkeep`.",
      "",
    ].join("\n"),
  );
  writeFileSync(path.join(outDir, ".gitkeep"), "");

  if (!skipInstall) {
    execFileSync("npm", ["install", "--omit=dev", "--no-fund", "--no-audit"], {
      cwd: outDir,
      stdio: "inherit",
      env: { ...process.env, npm_config_update_notifier: "false" },
    });
  }

  const scriptOut = path.join(outDir, RUNTIME_SCRIPT_NAME);
  if (!existsSync(scriptOut)) {
    throw new Error(`runtime scaffold missing script at ${scriptOut}`);
  }
  if (
    !skipInstall &&
    !existsSync(path.join(outDir, "node_modules", "@cursor", "sdk"))
  ) {
    throw new Error("npm install did not produce node_modules/@cursor/sdk");
  }

  return { outDir, scriptOut, sdkVersion, skipInstall };
}

function main() {
  const skipInstall = process.argv.includes("--skip-install");
  const root = repoRoot();
  const result = writeRuntimeScaffold({
    outDir: runtimeOutDir(root),
    sdkVersion: readSdkVersion(root),
    scriptSrc: sourceScriptPath(root),
    skipInstall,
  });
  console.log(
    `Cursor runtime ready at ${result.outDir} (sdk ${result.sdkVersion}${
      skipInstall ? ", skip-install" : ""
    })`,
  );
}

const isMain =
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  main();
}
